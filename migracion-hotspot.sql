-- VillaNet: venta automatica de fichas del hotspot (Clip)
-- Correr una sola vez en el SQL Editor del Supabase de VillaNet.
create table if not exists hotspot_fichas (
  codigo text primary key,
  tipo text not null,
  estado text not null default 'disponible',  -- disponible | vendida
  venta_id uuid,
  vendida_at timestamptz,
  creada_at timestamptz not null default now()
);
create index if not exists hotspot_fichas_disp on hotspot_fichas (tipo, estado);

create table if not exists hotspot_ventas (
  id uuid primary key default gen_random_uuid(),
  tipo text not null,
  monto numeric(10,2) not null,
  estado text not null default 'pendiente',  -- pendiente | pagada | expirada | cancelada | sin_fichas | revisar
  payment_request_id text unique,
  codigo text,
  receipt_no text,
  creada_at timestamptz not null default now(),
  pagada_at timestamptz
);

alter table hotspot_fichas enable row level security;
alter table hotspot_ventas enable row level security;
-- (sin policies: solo el backend con la service key puede leer/escribir)

